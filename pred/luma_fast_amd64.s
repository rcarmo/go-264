// raw signed16 horizontal sums; clipped half-pel output, eight pixels/lane group.
TEXT ·lumaH16(SB), NOSPLIT, $0-40
 MOVQ raw+0(FP), DI
 MOVQ half+8(FP), BX
 MOVQ src+16(FP), SI
 MOVQ rows+24(FP), R8
 MOVQ width+32(FP), R9
 PXOR X7, X7
h_row:
 XORQ R10, R10
h_col:
 MOVQ 0(SI)(R10*1), X0
 PUNPCKLBW X7, X0
 MOVQ 1(SI)(R10*1), X1
 PUNPCKLBW X7, X1
 MOVQ 2(SI)(R10*1), X2
 PUNPCKLBW X7, X2
 MOVQ 3(SI)(R10*1), X3
 PUNPCKLBW X7, X3
 MOVQ 4(SI)(R10*1), X4
 PUNPCKLBW X7, X4
 MOVQ 5(SI)(R10*1), X5
 PUNPCKLBW X7, X5
 PADDW X5, X0
 PADDW X4, X1
 PADDW X3, X2
 MOVOU X1, X3
 PSLLW $2, X1
 PADDW X3, X1
 MOVOU X2, X3
 PSLLW $4, X2
 PSLLW $2, X3
 PADDW X3, X2
 PSUBW X1, X0
 PADDW X2, X0
 MOVOU X0, (DI)(R10*2)
 PADDW ·lumaRound16(SB), X0
 PSRAW $5, X0
 PACKUSWB X7, X0
 MOVQ X0, (BX)(R10*1)
 ADDQ $8, R10
 CMPQ R10, R9
 JL h_col
 ADDQ $24, SI
 ADDQ $32, DI
 ADDQ $16, BX
 DECQ R8
 JNZ h_row
 RET

