// Exact rounded byte average. Never writes row padding or reads past width.
TEXT ·lumaAvg(SB), NOSPLIT, $0-64
 MOVQ out+0(FP), DI
 MOVQ outStride+8(FP), R11
 MOVQ a+16(FP), SI
 MOVQ aStride+24(FP), R12
 MOVQ b+32(FP), BX
 MOVQ bStride+40(FP), R13
 MOVQ w+48(FP), R9
 MOVQ h+56(FP), R8
avg_row:
 XORQ R10, R10
 CMPQ R9, $16
 JNE avg_8
 MOVOU (SI), X0
 MOVOU (BX), X1
 PAVGB X1, X0
 MOVOU X0, (DI)
 JMP avg_next
avg_8:
 CMPQ R9, $8
 JL avg_4
 MOVQ (SI), X0
 MOVQ (BX), X1
 PAVGB X1, X0
 MOVQ X0, (DI)
 MOVQ $8, R10
avg_4:
 MOVQ R9, AX
 SUBQ R10, AX
 CMPQ AX, $4
 JL avg_tail
 MOVL (SI)(R10*1), X0
 MOVL (BX)(R10*1), X1
 PAVGB X1, X0
 MOVL X0, (DI)(R10*1)
 ADDQ $4, R10
avg_tail:
 CMPQ R10, R9
 JGE avg_next
 MOVBLZX (SI)(R10*1), AX
 MOVBLZX (BX)(R10*1), DX
 ADDL DX, AX
 INCL AX
 SHRL $1, AX
 MOVB AX, (DI)(R10*1)
 INCQ R10
 JMP avg_tail
avg_next:
 ADDQ R11, DI
 ADDQ R12, SI
 ADDQ R13, BX
 DECQ R8
 JNZ avg_row
 RET
