// func filterChroma2StrongSSE2(lanes *chromaVerticalLanes, alpha, beta int)
TEXT ·filterChroma2StrongSSE2(SB), NOSPLIT, $0-24
	MOVQ lanes+0(FP), DI
	MOVOU ·deblockOnesW(SB), X14
	MOVQ alpha+8(FP), AX
	IMULL $65537, AX
	MOVD AX, X12
	PSHUFL $0, X12, X12
	MOVQ beta+16(FP), AX
	IMULL $65537, AX
	MOVD AX, X11
	PSHUFL $0, X11, X11
	MOVQ 8(DI), X0
	MOVQ 16(DI), X1
	MOVQ 0(DI), X2
	MOVQ 24(DI), X3
	// Overall condition mask.
	MOVOU X0, X4
	PSUBW X1, X4
	MOVOU X4, X5
	PSRAW $15, X5
	PXOR X5, X4
	PSUBW X5, X4
	MOVOU X12, X8
	PCMPGTW X4, X8
	MOVOU X2, X4
	PSUBW X0, X4
	MOVOU X4, X5
	PSRAW $15, X5
	PXOR X5, X4
	PSUBW X5, X4
	MOVOU X11, X9
	PCMPGTW X4, X9
	PAND X9, X8
	MOVOU X3, X4
	PSUBW X1, X4
	MOVOU X4, X5
	PSRAW $15, X5
	PXOR X5, X4
	PSUBW X5, X4
	MOVOU X11, X9
	PCMPGTW X4, X9
	PAND X9, X8
	// new p0 = (2*p1+p0+q1+2)>>2, selected by mask.
	MOVOU X2, X4
	PSLLW $1, X4
	PADDW X0, X4
	PADDW X3, X4
	PADDW ·deblockTwoW(SB), X4
	PSRLW $2, X4
	PAND X8, X4
	MOVOU X8, X5
	PXOR ·deblockAllOnes(SB), X5
	PAND X5, X0
	POR X0, X4
	MOVQ X4, 8(DI)
	// new q0 = (2*q1+q0+p1+2)>>2, selected by mask.
	MOVOU X3, X4
	PSLLW $1, X4
	PADDW X1, X4
	PADDW X2, X4
	PADDW ·deblockTwoW(SB), X4
	PSRLW $2, X4
	PAND X8, X4
	PAND X5, X1
	POR X1, X4
	MOVQ X4, 16(DI)
	RET

