sb_loop:
	CMPQ CX, $2
	JL sb_tail
	MOVUPD (SI), X0
	MULPD X7, X0
	MOVUPD X0, (DI)
	ADDQ $16, SI
	ADDQ $16, DI
	SUBQ $2, CX
	JMP sb_loop
