//go:build amd64 && !purego

#include "textflag.h"

// 8x8 int16 transpose: unpack words, then dwords, then qwords. No conversion,
// rounding or alignment assumption; source and destination are disjoint.
TEXT ·transpose8SSE2(SB), NOSPLIT, $0-16
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVUPD 0(SI), X0
	MOVUPD 16(SI), X1
	MOVUPD 32(SI), X2
	MOVUPD 48(SI), X3
	MOVUPD 64(SI), X4
	MOVUPD 80(SI), X5
	MOVUPD 96(SI), X6
	MOVUPD 112(SI), X7
	MOVAPD X0, X8
	PUNPCKLWL X1, X0
	PUNPCKHWL X1, X8
	MOVAPD X2, X9
	PUNPCKLWL X3, X2
	PUNPCKHWL X3, X9
	MOVAPD X4, X10
	PUNPCKLWL X5, X4
	PUNPCKHWL X5, X10
	MOVAPD X6, X11
	PUNPCKLWL X7, X6
	PUNPCKHWL X7, X11
	MOVAPD X0, X1
	PUNPCKLLQ X2, X0
	PUNPCKHLQ X2, X1
	MOVAPD X8, X3
	PUNPCKLLQ X9, X8
	PUNPCKHLQ X9, X3
	MOVAPD X4, X5
	PUNPCKLLQ X6, X4
	PUNPCKHLQ X6, X5
	MOVAPD X10, X7
	PUNPCKLLQ X11, X10
	PUNPCKHLQ X11, X7
	MOVAPD X0, X2
	PUNPCKLQDQ X4, X0
	PUNPCKHQDQ X4, X2
	MOVUPD X0, 0(DI)
	MOVUPD X2, 16(DI)
	MOVAPD X1, X2
	PUNPCKLQDQ X5, X1
	PUNPCKHQDQ X5, X2
	MOVUPD X1, 32(DI)
	MOVUPD X2, 48(DI)
	MOVAPD X8, X2
	PUNPCKLQDQ X10, X8
	PUNPCKHQDQ X10, X2
	MOVUPD X8, 64(DI)
	MOVUPD X2, 80(DI)
	MOVAPD X3, X2
	PUNPCKLQDQ X7, X3
	PUNPCKHQDQ X7, X2
	MOVUPD X3, 96(DI)
	MOVUPD X2, 112(DI)
	RET
